const assert=require('node:assert/strict');
const law=require('../assets/law-model.js');
const old={text:'Gammal',expires:{date:null,label:'den dag som regeringen bestämmer'}};
const neu={text:'Ny',inForce:{date:null,label:'den dag som regeringen bestämmer'}};
let r=law.resolve({type:'para',number:'3',text:'Gammal',versions:[old,neu]},'2026-10-25');
assert.equal(r.current.text,'Gammal');
assert.equal(r.others[0].text,'Ny');
assert.equal(law.describe(r.others[0]),'Kommande lydelse · träder i kraft den dag regeringen bestämmer');
const dated=[{text:'A',expires:{date:'2027-01-01'}},{text:'B',inForce:{date:'2027-01-01'}}];
assert.equal(law.resolve({versions:dated},'2026-12-31').current.text,'A');
assert.equal(law.resolve({versions:dated},'2027-01-01').current.text,'B');
assert.equal(law.resolve({versions:dated},'2027-01-01').others.length,0,'upphörd lydelse döljs');
const future=law.resolve({versions:[{text:'Ny paragraf',inForce:{date:'2027-01-01'}}]},'2026-10-25');
assert.equal(future.pending,true);
assert.equal(law.describe(future.current),'Kommande lydelse · träder i kraft 1 januari 2027');
assert.equal(law.resolve({text:'Enkel',amendedBy:'2020:1'}).current.amendedBy,'2020:1');
console.log('Lydelser: val av gällande och kommande lydelse godkänt');
const doc={chapters:[{number:'1',items:[{type:'para',number:'1',text:'A'},{type:'para',number:'2',text:'B'}]}]};
const before=law.snapshot(doc);
const after={chapters:[{number:'1',items:[{type:'para',number:'1',text:'A ändrad'},{type:'para',number:'3',text:'C'}]}]};
const d=law.diff(before,after);
assert.deepEqual([d.changed,d.added,d.removed],[['1|1'],['1|3'],['1|2']]);
assert.notEqual(before.hash,d.snapshot.hash);
console.log('Ändringsbevakning: jämförelse av ögonblicksbilder godkänd');
const dw=law.diffWords('Den som stjäl döms för stöld till fängelse i högst två år.','Den som stjäl döms för stöld till fängelse i högst tre år.');
assert.deepEqual(dw.filter(x=>x.type!=='same').map(x=>x.type+':'+x.text),['del:två','ins:tre']);
assert.equal(dw.filter(x=>x.type!=='ins').map(x=>x.text).join(''),'Den som stjäl döms för stöld till fängelse i högst två år.');
console.log('Jämför lydelser: ordvis skillnad godkänd');
